#!/usr/bin/env python3
"""
notify.py - Best-effort event hook: POST engine events to the manager.

Usage (from the Asterisk dialplan or swu_ike tunnel hooks):
  notify.py <event> [arg1] [arg2] ...

Call events carry <asterisk-linkedid> <trace-id> before their normal arguments.
The trace ID is generated by the initiating client for outgoing calls and by
Asterisk for incoming calls, then propagated to every component.

The patched Asterisk SMS module and tunnel transitions use the durable event
outbox. Other events remain best effort.

Reads MANAGER_URL and VOWIFI_ID from /run/vowifi/engine.env (written by render.py).
Never fails the caller (all exceptions swallowed).
"""
import os
import sys
import json
import time


def append_json(path, value):
    """Append one indivisible JSONL record even when hooks run concurrently."""
    import fcntl
    os.makedirs(os.path.dirname(path), exist_ok=True)
    encoded = (json.dumps(value, separators=(",", ":")) + "\n").encode()
    with open(path, "ab", buffering=0) as output:
        fcntl.flock(output.fileno(), fcntl.LOCK_EX)
        output.write(encoded)
        fcntl.flock(output.fileno(), fcntl.LOCK_UN)


def load_env():
    env = {}
    path = os.environ.get("VOWIFI_ENV", "/run/vowifi/engine.env")
    try:
        with open(path) as f:
            for line in f:
                if "=" in line:
                    k, v = line.strip().split("=", 1)
                    env[k] = v
    except Exception:
        pass
    return env


def main():
    if len(sys.argv) < 2:
        return
    event = sys.argv[1]
    args = sys.argv[2:]
    env = load_env()
    manager_url = os.environ.get("MANAGER_URL") or env.get("MANAGER_URL", "")
    manager_token = os.environ.get("VOWIFI_MANAGER_TOKEN") or env.get("VOWIFI_MANAGER_TOKEN", "")
    inst_id = os.environ.get("VOWIFI_ID") or env.get("VOWIFI_ID", "1")
    payload = {"instance": inst_id, "event": event, "args": args}
    if event in ("tunnel_up", "tunnel_down"):
        generation = os.environ.get("VITI_TUNNEL_GENERATION", "")
        sequence = os.environ.get("VITI_TUNNEL_SEQUENCE", "")
        try:
            sequence = int(sequence)
        except ValueError:
            sequence = 0
        if generation and sequence > 0:
            payload["tunnel_generation"] = generation
            payload["tunnel_sequence"] = sequence
    # Call hooks pass Asterisk's Linkedid first. It is stable for every channel
    # and branch in the same call and lets the manager update exactly one row,
    # regardless of call duration or delayed/out-of-order delivery.
    if event in ("call_in", "call_out", "call_active", "call_result", "recording_track") and args:
        payload["call_id"] = args[0]
        if len(args) > 1:
            payload["trace_id"] = args[1]
            payload["args"] = args[2:]
        else:
            payload["args"] = args[1:]
    payload["recorded_at_ns"] = time.time_ns()
    diagnostics_enabled = os.environ.get("VOWIFI_DIAGNOSTICS_ENABLED", "0").lower() in ("1", "true", "yes", "on")
    if diagnostics_enabled:
        try:
            os.makedirs("/logs", exist_ok=True)
            append_json("/logs/events.jsonl", payload)
        except Exception:
            pass
    if event in ("tunnel_up", "tunnel_down") and payload.get("tunnel_generation"):
        queued = False
        try:
            import event_outbox
            event_outbox.enqueue_event(event, args, recorded_at_ns=payload["recorded_at_ns"], extra={
                "tunnel_generation": payload["tunnel_generation"],
                "tunnel_sequence": payload["tunnel_sequence"],
            })
            queued = True
        except Exception as error:
            if diagnostics_enabled:
                try:
                    append_json("/logs/event-delivery.jsonl", {
                        "at_ns": time.time_ns(), "event": event, "error": repr(error),
                    })
                except Exception:
                    pass
        if queued:
            return
    if not manager_url:
        return
    try:
        import requests
        import urllib3
        urllib3.disable_warnings()
        headers = {"X-Viti-Engine-Token": manager_token} if manager_token else {}
        response = requests.post(f"{manager_url.rstrip('/')}/api/engine/event",
                                 json=payload, headers=headers, timeout=10, verify=False)
        if diagnostics_enabled:
            append_json("/logs/event-delivery.jsonl", {
                "at_ns": time.time_ns(), "event": event, "call_id": payload.get("call_id", ""),
                "trace_id": payload.get("trace_id", ""),
                "status": response.status_code, "response": response.text,
            })
    except Exception as error:
        if diagnostics_enabled:
            try:
                append_json("/logs/event-delivery.jsonl", {
                    "at_ns": time.time_ns(), "event": event, "call_id": payload.get("call_id", ""),
                    "trace_id": payload.get("trace_id", ""),
                    "error": repr(error),
                })
            except Exception:
                pass


if __name__ == "__main__":
    main()
